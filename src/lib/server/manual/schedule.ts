export type Frequency = 'weekly' | 'biweekly' | 'monthly';

export interface Schedule {
	frequency: Frequency;
	/** weekly/biweekly: ISO weekday 1 (Mon) to 7 (Sun). monthly: day of month 1 to 31. */
	anchor: number;
	startDate: string;
	endDate: string | null;
}

const MAX_OCCURRENCES = 5000;

const toMs = (iso: string) => {
	const [y, m, d] = iso.split('-').map(Number);
	return Date.UTC(y, m - 1, d);
};
const fromMs = (ms: number) => new Date(ms).toISOString().slice(0, 10);

export const addDays = (iso: string, days: number) => fromMs(toMs(iso) + days * 86_400_000);

/** ISO weekday: Monday = 1 ... Sunday = 7. */
export function weekdayOf(iso: string): number {
	const d = new Date(toMs(iso)).getUTCDay();
	return d === 0 ? 7 : d;
}

const daysInMonth = (year: number, month: number) =>
	new Date(Date.UTC(year, month, 0)).getUTCDate();

/** Local calendar date as YYYY-MM-DD (the household's "today"). */
export function todayIso(now = new Date()): string {
	const p = (n: number) => String(n).padStart(2, '0');
	return `${now.getFullYear()}-${p(now.getMonth() + 1)}-${p(now.getDate())}`;
}

/**
 * Dates generated by a schedule inside [from, to] (inclusive). The series is always computed
 * from `startDate`, so the result for a date never depends on the window asked for:
 * weekly/biweekly start at the first anchor weekday on or after the start date; monthly uses
 * the anchor day clamped to the end of short months (31 -> 28/29/30).
 */
export function occurrences(s: Schedule, from: string, to: string): string[] {
	const last = s.endDate && s.endDate < to ? s.endDate : to;
	const out: string[] = [];
	if (last < from || last < s.startDate) return out;
	const push = (d: string) => {
		if (d >= from && d >= s.startDate && d <= last) out.push(d);
	};
	if (s.frequency === 'monthly') {
		let [y, m] = s.startDate.split('-').map(Number);
		for (let i = 0; i < MAX_OCCURRENCES; i++, m++) {
			if (m > 12) {
				m = 1;
				y++;
			}
			const day = Math.min(s.anchor, daysInMonth(y, m));
			const d = `${y}-${String(m).padStart(2, '0')}-${String(day).padStart(2, '0')}`;
			if (d > last) break;
			push(d);
		}
		return out;
	}
	const step = s.frequency === 'weekly' ? 7 : 14;
	let d = s.startDate;
	while (weekdayOf(d) !== s.anchor) d = addDays(d, 1);
	for (let i = 0; i < MAX_OCCURRENCES && d <= last; i++, d = addDays(d, step)) push(d);
	return out;
}
